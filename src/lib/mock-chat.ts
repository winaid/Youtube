export async function generateChatResponse(
  userMessage: string,
  personaId: string
): Promise<string> {
  await new Promise((resolve) => setTimeout(resolve, 1000));

  const persona = storyPersonas.find((p) => p.id === personaId);
  if (!persona) return "페르소나를 찾을 수 없습니다.";

  const lowerMsg = userMessage.toLowerCase();

  // 키워드 매칭으로 적절한 역사 스토리 반환
  if (lowerMsg.includes("조선") || lowerMsg.includes("한의원") || lowerMsg.includes("후각") || lowerMsg.includes("냄새")) {
    return historyStories["조선"];
  }
  if (lowerMsg.includes("로마") || lowerMsg.includes("성형") || lowerMsg.includes("비포") || lowerMsg.includes("라이브") || lowerMsg.includes("갈레노스")) {
    return historyStories["로마"];
  }
  if (lowerMsg.includes("프랑스") || lowerMsg.includes("치과") || lowerMsg.includes("투명") || lowerMsg.includes("포샤르")) {
    return historyStories["프랑스"];
  }
  if (lowerMsg.includes("일본") || lowerMsg.includes("에도") || lowerMsg.includes("리뷰") || lowerMsg.includes("하나오카")) {
    return historyStories["일본"];
  }
  if (lowerMsg.includes("중국") || lowerMsg.includes("한나라") || lowerMsg.includes("화타") || lowerMsg.includes("맞춤")) {
    return historyStories["중국"];
  }

  // 기본 응답
  return `좋은 질문이야! ㅋㅋ

"${userMessage}" 관련해서 역사 속 마케팅 사례를 찾아볼게.

아래 키워드로 다시 물어봐:
- "조선시대 의원" → 후각 마케팅 전략
- "고대 로마 의사" → 라이브 퍼포먼스 마케팅
- "프랑스 치과" → 투명성 콘텐츠 마케팅
- "일본 에도시대" → 리뷰/기록 마케팅
- "중국 한나라" → 맞춤형 진료 마케팅

실제 AI 연동하면 어떤 주제든 역사 속에서 찾아서
병의원 마케팅 쇼츠 시나리오로 만들어줄 수 있어!`;
}
